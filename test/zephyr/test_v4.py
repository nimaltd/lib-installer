def test_project_cmake_goes_into_the_applications_cmakelists_by_its_place(library, app, nobody, no_network):
    root = app()
    project = {"cmake": {"before-zephyr": ['list(APPEND EXTRA_DTC_OVERLAY_FILE "{library}/dts/gcore.overlay")'],
                         "after-zephyr": ["target_compile_definitions(app PRIVATE GCORE_APP=1)"]}}

    assert _install(_gcore(library, project=project, files={"dts/gcore.overlay": "/ { };\n"}), root) == 0

    cmake = read(root / "CMakeLists.txt")
    assert ('list(APPEND EXTRA_DTC_OVERLAY_FILE "${CMAKE_CURRENT_SOURCE_DIR}/modules/gcore/dts/gcore.overlay")'
            in cmake)
    assert (cmake.index("lib-installer: gcore/before-zephyr >>>") < cmake.index("find_package(Zephyr")
            < cmake.index("lib-installer: gcore/after-zephyr >>>"))


