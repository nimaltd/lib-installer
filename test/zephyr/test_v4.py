@pytest.mark.parametrize("crlf", [False, True])
def test_an_uninstall_gives_the_application_back_as_it_was(library, app, nobody, no_network, crlf):
    root = app(prj="CONFIG_GPIO=y\n", crlf=crlf)
    before = {name: read(root / name) for name in ("CMakeLists.txt", "prj.conf")}
    project = {"conf": {"Its settings": [{"LOG=n": "no messages"}]},
               "cmake": {"after-zephyr": {"Its definition": ["target_compile_definitions(app PRIVATE G=1)"]}}}
    _install(_gcore(library, project=project, own={"conf": {"Every build": CONF}}), root)

    cmake = read(root / "CMakeLists.txt")
    assert "gcore/zephyr.conf" in cmake
    assert ("\r\n" in cmake) == crlf
    assert ("\r\n" in read(root / "prj.conf")) == crlf

    assert _uninstall(root) == 0

    assert {name: read(root / name) for name in before} == before
    assert not (root / "modules" / "gcore").exists()


def test_a_library_with_its_own_module_gets_the_fragment_too(library, app, nobody, no_network, capsys):
    own = "name: gcore\nbuild:\n  cmake: zephyr\n  kconfig: zephyr/Kconfig\n"
    lib = _gcore(library, own={"conf": CONF}, extra={"extras": ["zephyr/module.yml"]},
                 files={"zephyr/module.yml": own})
    root = app()

    assert _install(lib, root) == 0

    folder = root / "modules" / "gcore" / "zephyr"
    assert sorted(p.name for p in folder.iterdir()) == ["gcore.conf", "module.yml"]
