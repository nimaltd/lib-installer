"""
What 4.0.0 brings to a Zephyr application: the zephyr section says where each
line it writes goes. Under project, the application's own files: conf, the
library's block in prj.conf, beside its switch; sysbuild, its block in
sysbuild.conf; and cmake, its blocks in CMakeLists.txt, under before-zephyr
and after-zephyr. Under library, its own folder: kconfig, the defaults of its
Kconfig; conf, its Kconfig fragment, zephyr/<name>.conf, which a block of the
application's CMakeLists.txt adds to EXTRA_CONF_FILE, read after prj.conf; and
cmake, the lines of its own CMakeLists.txt. The library's switch is
zephyr.symbol.

Every list can be given in groups under their titles, and a setting with a
note: each file written carries a title between two lines of stars, and a note
above its setting. The keys from before 4.0.0 are refused in a manifest asking
for it, with where they went, and the new ones in a manifest asking for less,
which keeps the meanings it was written for.
"""

import json
import os
import re

import pytest
from conftest import read

from lib_installer.core import cli, manifest
from lib_installer.core.manifest import ManifestError
from lib_installer.zephyr import app as appfile

FOUR = {"lib_installer": "4.0.0"}
BEFORE = {"lib_installer": "3.0.0"}

STARS = "# " + "*" * 78

CONF = ["BT_AUTO_PHY_PERIPHERAL_2M", "CONFIG_BT_CTLR_SDC_MAX_CONN_EVENT_LEN_DEFAULT=4000000",
        'BT_DEVICE_NAME="gcore"', "NCS_MCUBOOT_IMGTOOL_SET_ROM_FIXED_ADDRESS=n"]

LINES = ("CONFIG_BT_AUTO_PHY_PERIPHERAL_2M=y\n"
         "CONFIG_BT_CTLR_SDC_MAX_CONN_EVENT_LEN_DEFAULT=4000000\n"
         'CONFIG_BT_DEVICE_NAME="gcore"\n'
         "CONFIG_NCS_MCUBOOT_IMGTOOL_SET_ROM_FIXED_ADDRESS=n\n")

HEADER = ("# Generated by lib-installer for gcore 1.2.0. Written again on\n"
          "# every install and update, so a change made here does not last.\n"
          "#\n"
          "# gcore's settings, from zephyr.library.conf in its installer.yml. The\n"
          "# application's CMakeLists.txt adds this file to EXTRA_CONF_FILE, so Zephyr\n"
          "# reads it after prj.conf, and a line here wins over one there.\n"
          "\n")

BLOCK = ("# >>> lib-installer: gcore/zephyr.conf >>>\n"
         "# gcore's Kconfig settings, from zephyr.library.conf in its installer.yml,\n"
         "# read after prj.conf. Written again on every install.\n"
         'list(APPEND EXTRA_CONF_FILE "${CMAKE_CURRENT_SOURCE_DIR}/modules/gcore/zephyr/gcore.conf")\n'
         "# <<< lib-installer: gcore/zephyr.conf <<<\n")

OPEN = ("# >>> lib-installer: gcore >>>\n"
        "# Added by lib-installer, and written again on every install, so set\n"
        "# gcore's settings below this block rather than in it.\n")

CLOSE = "# <<< lib-installer: gcore <<<\n"

# The switch, last in the block of prj.conf, a group of its own under the
# library's name.
SWITCH = f"{STARS}\n# gcore\n{STARS}\nCONFIG_GCORE=y\n"


def _block(*lines):
    """gcore's block in prj.conf: its lines, plain, then the switch, after a blank line each."""
    body = "".join(f"{line}\n" for line in lines)

    return OPEN + "\n" + body + ("\n" if body else "") + SWITCH + CLOSE


def _gcore(library, project=None, own=None, requires=FOUR, symbol="GCORE", name="gcore", zephyr=None,
           extra=None, files=None, platform="zephyr"):
    """gcore, asking for 4.0.0: its switch, and what it writes under project and under library."""
    part = {"symbol": symbol} if symbol is not None else {}

    if project is not None:
        part["project"] = project

    if own is not None:
        part["library"] = own

    part.update(zephyr or {})

    return library(name=name, headers=("src/gcore.h",), sources=("src/gcore.c",), requires=requires,
                   zephyr=part, extra=dict({"platform": platform, "once": []}, **(extra or {})), files=files)


def _install(source, root, *more):
    return cli.main([str(source), "--project", str(root), "--dir", "modules/gcore", *more])


def _uninstall(root):
    return cli.main(["--uninstall", "gcore", "--project", str(root)])


def _zephyr(root, name):
    """A file of gcore's own zephyr folder in the application."""
    return root / "modules" / "gcore" / "zephyr" / name


