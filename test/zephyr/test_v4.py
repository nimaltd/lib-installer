    assert read(folder / "gcore.conf").endswith(LINES)
    assert "gcore has its own zephyr/module.yml, used as it is. Wrote zephyr/gcore.conf." in capsys.readouterr().out

    assert _uninstall(root) == 0
    assert not (root / "modules" / "gcore").exists()
    assert "gcore/zephyr.conf" not in read(root / "CMakeLists.txt")


