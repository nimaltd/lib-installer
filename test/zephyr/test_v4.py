def test_an_options_cmake_is_under_project_and_library(library, app, nobody, no_network):
    root = app()
    options = {"report": {"description": "Say the board", "zephyr": {
        "project": {"cmake": {"after-zephyr": ['message(STATUS "${BOARD}")']}},
        "library": {"cmake": ["zephyr_library_compile_definitions(GCORE_REPORT=1)"]}}}}
    source = _gcore(library, extra={"options": options})

