def test_a_second_install_changes_nothing(library, app, nobody, no_network, capsys):
    root = app()
    lib = _gcore(library, own={"conf": CONF})
    _install(lib, root)
    cmake = read(root / "CMakeLists.txt")
    os.utime(_zephyr(root, "gcore.conf"), (1000000000, 1000000000))
    backups = sorted(p.name for p in root.rglob("*.bak"))
    capsys.readouterr()

    assert _install(lib, root) == 0

    assert read(root / "CMakeLists.txt") == cmake
    assert _zephyr(root, "gcore.conf").stat().st_mtime == 1000000000
    assert sorted(p.name for p in root.rglob("*.bak")) == backups
    assert "gcore_lib is up to date." in capsys.readouterr().out


