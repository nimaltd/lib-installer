def test_the_fragments_block_keeps_its_place_among_the_cmake_blocks(library, app, nobody, no_network):
    """The blocks go above find_package(Zephyr) one by one, so the order has to come back the same."""
    root = app()
    project = {"cmake": {"before-zephyr": ['list(APPEND EXTRA_DTC_OVERLAY_FILE "{library}/dts/gcore.overlay")'],
                         "after-zephyr": ["target_compile_definitions(app PRIVATE GCORE_APP=1)"]}}
    lib = _gcore(library, project=project, own={"conf": CONF}, files={"dts/gcore.overlay": "/ { };\n"})

    _install(lib, root)
    first = read(root / "CMakeLists.txt")
    _install(lib, root)

    assert read(root / "CMakeLists.txt") == first
    assert (first.index("lib-installer: gcore >>>") < first.index("lib-installer: gcore/zephyr.conf >>>")
            < first.index("lib-installer: gcore/before-zephyr >>>") < first.index("find_package(Zephyr")
            < first.index("lib-installer: gcore/after-zephyr >>>"))


def test_a_line_adding_to_extra_conf_file_is_a_block_apart(library, app, nobody, no_network):
    """A library can add a file of its own to EXTRA_CONF_FILE too, beside its fragment."""
    root = app(prj="")
    before = read(root / "CMakeLists.txt")
    project = {"cmake": {"before-zephyr": ['list(APPEND EXTRA_CONF_FILE "${CMAKE_CURRENT_SOURCE_DIR}/extra.conf")']}}
    lib = _gcore(library, project=project, own={"conf": CONF})

    _install(lib, root)
    _install(lib, root)

    cmake = read(root / "CMakeLists.txt")
    assert cmake.count(">>> lib-installer: gcore/before-zephyr >>>") == 1
    assert cmake.count(">>> lib-installer: gcore/zephyr.conf >>>") == 1
    assert cmake.count("EXTRA_CONF_FILE") == 2

    assert _uninstall(root) == 0
    assert read(root / "CMakeLists.txt") == before


def test_the_record_keeps_the_block_and_an_edit_inside_it_is_noticed(library, app, nobody, no_network, capsys):
    root = app()
    lib = _gcore(library, own={"conf": CONF})
    _install(lib, root)

    record = json.loads((root / ".lib-installer.json").read_text(encoding="utf-8"))
    assert "gcore/zephyr.conf" in record["libraries"]["gcore"]["blocks"]["CMakeLists.txt"]

    path = root / "CMakeLists.txt"
    path.write_bytes(read(path).replace("/zephyr/gcore.conf", "/zephyr/mine.conf").encode("utf-8"))
    capsys.readouterr()
    _install(lib, root)

    assert "Your change inside the gcore/zephyr.conf block is replaced" in capsys.readouterr().out
    assert BLOCK in read(path)


