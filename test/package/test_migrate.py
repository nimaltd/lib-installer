"""
A project an installer before 3.0.0 installed into, moved over to lib-installer
on the first run: its record, and the markers of its blocks in the project's
files. Each project here is made by lib-installer, then turned back into what
the platform's installer before 3.0.0 left, the way a user's project is.
"""

import json
import re

import pytest

import lib_installer
from conftest import run
from lib_installer.core import installer

LEGACY = re.compile(r"(?m)^([ \t]*[#;][ \t]*)(>>>|<<<) lib-installer: ")


def _files(*roots):
    """Every file under roots, but the backups."""
    return [path for root in roots for path in root.rglob("*") if path.is_file() and ".bak" not in path.suffixes]


def _downgrade(legacy, *roots):
    """
    Make what lib-installer wrote under roots what legacy wrote: its record,
    the markers of its blocks, and the first line of the files it generates.
    What is inside each block stays as it is, as it would after an update.
    """
    for path in _files(*roots):
        if path.name == ".lib-installer.json":
            data = json.loads(path.read_text(encoding="utf-8"))
            del data["platform"]
            data["record"] = 2
            (path.parent / f".{legacy}.json").write_text(json.dumps(data), encoding="utf-8")
            path.unlink()
            continue

        try:
            text = path.read_bytes().decode("utf-8")
        except UnicodeDecodeError:
            continue

        old = LEGACY.sub(lambda found: f"{found.group(1)}{found.group(2)} {legacy}: ", text)
        old = old.replace("# Generated by lib-installer", f"# Generated by {legacy}")

        if old != text:
            path.write_bytes(old.encode("utf-8"))


def _marked(*roots):
    """{file: the text of every marker line in it}, for every file with one."""
    found = {}

    for path in _files(*roots):
        text = path.read_bytes().decode("utf-8", "replace")
        lines = [line for line in text.splitlines() if re.match(r"^[ \t]*[#;][ \t]*(>>>|<<<) ", line)]

        if lines:
            found[path] = lines

    return found


# A library with a define, which pio puts in platformio.ini, so every platform
# has a block of its own in the project's files.
EXTRA = {"install": {"defines": ["DEMO_SIZE=8"]}}


@pytest.mark.parametrize("platform", ["stm32", "zephyr", "esp32", "pio"])
@pytest.mark.parametrize("crlf", [False, True], ids=["lf", "crlf"])
def test_a_project_of_the_installer_before_moves_over(library, project, platform, crlf, capsys):
    root = project(platform, crlf=crlf)
    source = library(platform=platform, extra=EXTRA)
    # Outside components, so ESP-IDF has a block in the project's CMakeLists.txt.
    where = ["--dir", "libs/demo"] if platform == "esp32" else []
    assert run(source, "--project", root, *where) == 0
    written = {path: path.read_bytes() for path in _files(root)}
    markers = _marked(root)
    legacy = f"{platform}-installer"
    _downgrade(legacy, root)
    capsys.readouterr()

    assert markers
    assert run(source, "--project", root, *where) == 0

    said = capsys.readouterr().out
    record = json.loads((root / ".lib-installer.json").read_text(encoding="utf-8"))

    assert f"Moved over from {legacy} to lib-installer" in said
    assert record["platform"] == platform
    assert set(record["libraries"]) == {"demo"}
    assert not (root / f".{legacy}.json").exists()
    assert list(root.glob(f".{legacy}.json.*.bak"))
    # One block of each, where it was, and nothing of the old name: not a
    # second block beside the old one.
    assert _marked(root) == markers

    # Each file the markers moved in was saved first.
    for path in markers:
        assert list(path.parent.glob(f"{path.name}.*.bak")), path
    assert legacy not in "".join(path.read_bytes().decode("utf-8", "replace") for path in _files(root))

    for path, before in written.items():
        if path.name != ".lib-installer.json":
            assert path.read_bytes() == before, path


@pytest.mark.parametrize("platform", ["stm32", "zephyr", "esp32", "pio"])
def test_an_uninstall_takes_out_what_the_installer_before_wrote(library, project, platform):
    root = project(platform)
    where = ["--dir", "libs/demo"] if platform == "esp32" else []
    assert run(library(platform=platform, extra=EXTRA), "--project", root, *where) == 0
    _downgrade(f"{platform}-installer", root)

    assert run("--uninstall", "demo", "--project", root) == 0

    assert _marked(root) == {}
    # The files it generated in the library's folder are its own, and go too.
    assert not any(path.read_bytes().startswith(b"# Generated by") for path in _files(root))


def test_each_file_is_saved_as_it_was_and_the_record_names_the_platform(library, project):
    root = project("zephyr", crlf=True)
    assert run(library(platform="zephyr"), "--project", root) == 0
    _downgrade("zephyr-installer", root)
    before = {name: (root / name).read_bytes() for name in ("CMakeLists.txt", "prj.conf", ".zephyr-installer.json")}

    for saved in root.glob("*.bak"):
        saved.unlink()

    lib_installer.use("zephyr")
    moved = installer.migrate(root)

    assert moved == [root / "CMakeLists.txt", root / "prj.conf", root / ".lib-installer.json"]
    assert json.loads((root / ".lib-installer.json").read_text(encoding="utf-8"))["platform"] == "zephyr"

    for name, held in before.items():
        assert [saved.read_bytes() for saved in root.glob(f"{name}.*.bak")] == [held], name

    # Once moved over, there is nothing more to move.
    assert installer.migrate(root) == []


def test_markers_in_every_kconfig_file_of_zephyr_move_over(library, project):
    root = project("zephyr", files={"debug.conf": "CONFIG_DEBUG=y\n"})
    source = library(platform="zephyr")
    assert run(source, "--project", root, "--conf", "debug.conf") == 0
    before = (root / "debug.conf").read_text(encoding="utf-8")
    _downgrade("zephyr-installer", root)

    assert run(source, "--project", root) == 0

    assert (root / "debug.conf").read_text(encoding="utf-8") == before
    assert "lib-installer" not in (root / "prj.conf").read_text(encoding="utf-8")


def test_an_arduino_record_in_the_libraries_folder_moves_over(library, project, sketchbook, capsys):
    root = project("arduino")
    libraries = sketchbook / "libraries"
    source = library(platform="arduino")
    assert run(source, "--project", root, "--into", "libraries") == 0
    properties = (libraries / "demo" / "library.properties").read_bytes()
    _downgrade("arduino-installer", libraries)
    capsys.readouterr()

    assert run(source, "--project", root, "--into", "libraries") == 0

    assert "Moved over from arduino-installer to lib-installer" in capsys.readouterr().out
    assert json.loads((libraries / ".lib-installer.json").read_text(encoding="utf-8"))["platform"] == "arduino"
    assert not (libraries / ".arduino-installer.json").exists()
    assert (libraries / "demo" / "library.properties").read_bytes() == properties


