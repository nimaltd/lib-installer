def test_the_old_record_says_which_platform_to_give(library, project, capsys):
    root = project("zephyr")
    assert run(library(platform="zephyr"), "--project", root) == 0
    _downgrade("zephyr-installer", root)
    capsys.readouterr()

    # A manifest from before 3.0.0 names no platform. The record is not taken
    # for it, but it is what the run says to give.
    assert run(library(name="older"), "--project", root) == 2

    assert "This project's record says zephyr, so add --platform zephyr." in capsys.readouterr().err

    assert run(library(name="older"), "--project", root, "--platform", "zephyr") == 0

    record = json.loads((root / ".lib-installer.json").read_text(encoding="utf-8"))
    assert set(record["libraries"]) == {"demo", "older"}


def test_an_uninstall_moves_over_first(library, project):
    root = project("zephyr")
    assert run(library(platform="zephyr"), "--project", root) == 0
    _downgrade("zephyr-installer", root)

    assert run("--uninstall", "demo", "--project", root) == 0

    assert "installer" not in (root / "CMakeLists.txt").read_text(encoding="utf-8")
    assert not (root / ".zephyr-installer.json").exists()


def test_a_project_with_both_records_is_left_as_it_is(library, project):
    root = project("zephyr")
    assert run(library(platform="zephyr"), "--project", root) == 0
    (root / ".zephyr-installer.json").write_text('{"record": 2, "libraries": {}}', encoding="utf-8")

    assert run(library(platform="zephyr"), "--project", root) == 0

    assert (root / ".zephyr-installer.json").read_text(encoding="utf-8") == '{"record": 2, "libraries": {}}'


def test_a_marker_of_another_installer_is_left_alone(library, project):
    root = project("zephyr", files={"other.cmake": "# >>> stm32-installer: x >>>\n# <<< stm32-installer: x <<<\n"})
    assert run(library(platform="zephyr"), "--project", root) == 0
    cmake = root / "CMakeLists.txt"
    cmake.write_text(cmake.read_text(encoding="utf-8") + "# >>> stm32-installer: x >>>\n", encoding="utf-8")
    _downgrade("zephyr-installer", root)

    assert run(library(platform="zephyr"), "--project", root) == 0

    assert "# >>> stm32-installer: x >>>" in cmake.read_text(encoding="utf-8")
